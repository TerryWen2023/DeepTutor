export function getSubjects(grade) {
  return getSubjectIds(grade).map((id) => ({ ...SUBJECTS[id] }));
}

export function getTopics(grade, subject) {
  const value = normalizeGrade(grade);
  if (!value || !getSubjects(value).some(({ id }) => id === subject)) return [];
  const topicBank = value >= 10 ? HIGH_SCHOOL_TOPICS : TOPICS;
  return (topicBank[subject]?.[value] || []).map((entry, index) => {
    const [title, description] = entry.split('|');
    return { id: `g${value}-${subject}-topic-${index + 1}`, title, description };
  });
}

export function getPractice(grade, subject) {
  const value = normalizeGrade(grade);
  const topics = getTopics(value, subject);
  if (!topics.length) return [];
  const practiceBank = value >= 10 ? HIGH_SCHOOL_PRACTICE : PRACTICE;
  return (practiceBank[subject]?.[value] || []).map(([topicIndex, question, options, answerIndex, explanation], index) => ({
    id: `g${value}-${subject}-q${index + 1}`,
    question,
    options: [...options],
    answerIndex,
    explanation,
    topic: topics[topicIndex].title,
    topicId: topics[topicIndex].id,
  }));
}

